"""Generate assets/js/data-ch23.js for binary-outcome and pricing labs."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "js" / "data-ch23.js"

np.random.seed(123)
n = 100000
nudge = np.random.binomial(1, 0.5, n)
age = np.random.gamma(10, 4, n)
income = np.random.gamma(20, 2, n) * 100
latent = np.random.normal(-4.5 + income * 0.001 + nudge + nudge * age * 0.01)
frame = pd.DataFrame(
    {
        "nudge": nudge,
        "age": age,
        "income": income,
        "latent": latent,
        "conversion": (latent > 0.1).astype(int),
        "low": (latent > 2).astype(int),
        "high": (latent > -2).astype(int),
    }
)


def effect(data, outcome):
    return float(data.loc[data.nudge == 1, outcome].mean() - data.loc[data.nudge == 0, outcome].mean())


def curve(outcome, prediction):
    ordered = frame.sort_values(prediction, ascending=False).reset_index(drop=True)
    rows = list(range(500, len(frame), len(frame) // 100)) + [len(frame)]
    values = [effect(ordered.head(row), outcome) for row in rows]
    return {
        "x": [round(row / len(frame) * 100, 3) for row in rows],
        "effect": [round(value, 5) for value in values],
    }


curves = {}
ates = {}
for key, outcome in [("latent", "latent"), ("conversion", "conversion"), ("low", "low"), ("high", "high")]:
    curves[key] = {
        "age": curve(outcome, "age"),
        "income": curve(outcome, "income"),
    }
    ates[key] = round(effect(frame, outcome), 6)

# conversion by income bin, for the S-curve
binned = frame.assign(bin=(frame.income / 100).astype(int) * 100).groupby("bin").conversion.mean()
sample = binned.iloc[:: max(1, len(binned) // 60)]

payload = {
    "n": int(n),
    "ate": ates,
    "means": {
        "conversion": round(float(frame.conversion.mean()), 6),
        "latent": round(float(frame.latent.mean()), 6),
        "low": round(float(frame.low.mean()), 6),
        "high": round(float(frame.high.mean()), 6),
        "age": round(float(frame.age.mean()), 4),
        "income": round(float(frame.income.mean()), 2),
    },
    "curves": curves,
    "sCurve": {
        "income": [int(index) for index in sample.index],
        "conversion": [round(float(value), 5) for value in sample.values],
    },
    "pricing": {
        "price": [5, 10, 15, 20],
        "a": [5350, 5300, 5000, 4500],
        "b": [5100, 5000, 4500, 3000],
    },
}
js = "/* Generated by tools/build-ch23-data.py; simulated with seed 123. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch23Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("means", payload["means"])
print("ate", ates)
