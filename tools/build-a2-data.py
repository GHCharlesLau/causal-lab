"""Generate assets/js/data-a2.js for the propensity-score note."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "invest_email.csv"
OUT = ROOT / "assets" / "js" / "data-a2.js"

email = pd.read_csv(SRC)
confounders = ["age", "income", "insurance", "invested"]


def weighted_sample(weights, seed=123, size=10000):
    rng = np.random.RandomState(seed)
    weights = np.asarray(weights, dtype=float)
    weights = weights / weights.sum()
    return email.iloc[rng.choice(len(email), size=size, replace=True, p=weights)]


weights = email.em1 / email.em1_ps + (1 - email.em1) / (1 - email.em1_ps)
weighted = weighted_sample(weights)


def corr_with_treatment(frame, treatment):
    return {
        col: round(float(frame[col].corr(frame[treatment])), 6)
        for col in confounders
    }


def histogram(series, treatment, bins=20):
    edges = np.linspace(0, 1, bins + 1)
    out = {"edges": [round(float(value), 3) for value in edges], "treated": [], "control": []}
    for i in range(bins):
        mask = (series >= edges[i]) & (series < edges[i + 1] if i < bins - 1 else series <= edges[i + 1])
        out["treated"].append(int((mask & (email[treatment] == 1)).sum()))
        out["control"].append(int((mask & (email[treatment] == 0)).sum()))
    return out


payload = {
    "n": int(len(email)),
    "treatedShare": round(float(email.em1.mean()), 6),
    "converted": round(float(email.converted.mean()), 6),
    "corr": {
        "raw": corr_with_treatment(email, "em1"),
        "weighted": corr_with_treatment(weighted, "em1"),
        "em3Raw": corr_with_treatment(email, "em3"),
        "em3Restricted": corr_with_treatment(email.query("age > 40"), "em3"),
    },
    "ps": {
        "em1": histogram(email.em1_ps, "em1"),
        "em3": histogram(email.em3_ps, "em3")
    },
    "maxWeight": round(float(weights.max()), 4),
    "row1014": {
        "ps": round(float(email.loc[1014, "em1_ps"]), 6),
        "weight": round(float(weights.loc[1014]), 4),
        "replications": int((weighted.index == 1014).sum())
    }
}
js = "/* Generated by tools/build-a2-data.py from invest_email.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.A2Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("raw", payload["corr"]["raw"])
print("weighted", payload["corr"]["weighted"])
print("em3", payload["corr"]["em3Raw"])
print("row1014", payload["row1014"])
