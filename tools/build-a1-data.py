"""Generate assets/js/data-a1.js for the orthogonalization note."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "ice_cream_sales.csv"
OUT = ROOT / "assets" / "js" / "data-a1.js"

prices = pd.read_csv(SRC)
rng = np.random.RandomState(123)
perm = rng.permutation(len(prices))
test = prices.iloc[perm[:5000]].copy()
train = prices.iloc[perm[5000:]].copy()

weekdays = sorted(prices.weekday.unique())


def design(frame, cols, intercept=True):
    parts = [np.ones(len(frame))] if intercept else []
    for col in cols:
        if col == "weekday":
            for wd in weekdays[1:]:
                parts.append((frame.weekday.values == wd).astype(float))
        else:
            parts.append(frame[col].values.astype(float))
    return np.column_stack(parts)


def fit(frame, y, cols):
    X = design(frame, cols)
    return np.linalg.lstsq(X, frame[y].values, rcond=None)[0]


beta_t = fit(test, "price", ["cost", "weekday", "temp"])
beta_y = fit(test, "sales", ["cost", "weekday", "temp"])
price_hat = design(test, ["cost", "weekday", "temp"]) @ beta_t
sales_hat = design(test, ["cost", "weekday", "temp"]) @ beta_y
test["price_res"] = test.price - price_hat
test["sales_res"] = test.sales - sales_hat


def slope(frame, x, y):
    xm = frame[x].mean()
    ym = frame[y].mean()
    return float(((frame[x] - xm) * (frame[y] - ym)).sum() / ((frame[x] - xm) ** 2).sum())


raw_slope = slope(test, "price", "sales")
price_res_slope = slope(test, "price_res", "sales")
both_slope = slope(test, "price_res", "sales_res")

# causal model on the training half
def cate_design(frame, price_shift=0.0):
    price = frame.price.values + price_shift
    cols = [np.ones(len(frame)), price, frame.cost.values, frame.temp.values]
    for wd in weekdays[1:]:
        cols.append((frame.weekday.values == wd).astype(float))
    cols += [price * frame.cost.values, price * frame.temp.values]
    for wd in weekdays[1:]:
        cols.append(price * (frame.weekday.values == wd))
    return np.column_stack(cols)


beta_m3 = np.linalg.lstsq(cate_design(train), train.sales.values, rcond=None)[0]
elasticity = (cate_design(test, 0.01) @ beta_m3 - cate_design(test) @ beta_m3) / 0.01
test["m3_pred"] = elasticity


def curve(frame, y, x, prediction):
    ordered = frame.sort_values(prediction, ascending=False).reset_index(drop=True)
    rows = list(range(50, len(ordered), len(ordered) // 100)) + [len(ordered)]
    values = [slope(ordered.head(row), x, y) for row in rows]
    gain = [values[i] * rows[i] / len(ordered) for i in range(len(rows))]
    return {
        "x": [round(row / len(ordered), 5) for row in rows],
        "gain": [round(value, 5) for value in gain],
    }


def elast(frame, y, x):
    return slope(frame, x, y)


debiased_curve = curve(test, "sales_res", "price_res", "m3_pred")
biased_curve = curve(test, "sales", "price", "m3_pred")

sample = test.sample(600, random_state=123)
payload = {
    "n": int(len(prices)),
    "nTest": int(len(test)),
    "corr": {
        "priceSales": round(float(test.price.corr(test.sales)), 6),
        "costPrice": round(float(test.cost.corr(test.price)), 6),
        "tempSales": round(float(test.temp.corr(test.sales)), 6),
    },
    "slope": {
        "raw": round(raw_slope, 5),
        "priceRes": round(price_res_slope, 5),
        "both": round(both_slope, 5),
    },
    "curves": {"debiased": debiased_curve, "biased": biased_curve},
    "end": {
        "debiased": round(min(debiased_curve["gain"]), 5),
        "biased": round(biased_curve["gain"][-1], 5),
    },
    "scatter": [
        {
            "price": round(float(row.price), 2),
            "sales": int(row.sales),
            "priceRes": round(float(row.price_res), 4),
            "salesRes": round(float(row.sales_res), 4),
        }
        for row in sample.itertuples()
    ],
}
js = "/* Generated by tools/build-a1-data.py from ice_cream_sales.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.A1Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("corr", payload["corr"], "slope", payload["slope"], "end", payload["end"])
