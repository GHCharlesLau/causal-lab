"""Generate assets/js/data-ch21.js for the S/T/X learner gain comparison."""
from __future__ import annotations

import json
import warnings
from pathlib import Path

import numpy as np
import pandas as pd
from lightgbm import LGBMRegressor
from sklearn.linear_model import LogisticRegression

warnings.filterwarnings("ignore")

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch21.js"

test = pd.read_csv(BASE / "invest_email_rnd.csv")
train = pd.read_csv(BASE / "invest_email_biased.csv")
y = "converted"
T = "em1"
X = ["age", "income", "insurance", "invested"]


def lt(**kwargs):
    return LGBMRegressor(random_state=123, verbose=-1, **kwargs)


# S-learner
s_learner = lt(max_depth=3, min_child_samples=30).fit(train[X + [T]], train[y])
s_cate = test.assign(
    cate=s_learner.predict(test[X].assign(**{T: 1}))
    - s_learner.predict(test[X].assign(**{T: 0}))
)

# T-learner
m0 = lt(max_depth=2, min_child_samples=60).fit(train.query(f"{T} == 0")[X], train.query(f"{T} == 0")[y])
m1 = lt(max_depth=2, min_child_samples=60).fit(train.query(f"{T} == 1")[X], train.query(f"{T} == 1")[y])
t_cate = test.assign(cate=m1.predict(test[X]) - m0.predict(test[X]))

# X-learner
m0x = lt(max_depth=2, min_child_samples=30).fit(train.query(f"{T} == 0")[X], train.query(f"{T} == 0")[y])
m1x = lt(max_depth=2, min_child_samples=30).fit(train.query(f"{T} == 1")[X], train.query(f"{T} == 1")[y])
g = LogisticRegression(solver="lbfgs", C=1e6, max_iter=1000).fit(train[X], train[T])
d_train = np.where(
    train[T] == 0,
    m1x.predict(train[X]) - train[y],
    train[y] - m0x.predict(train[X]),
)
mx0 = lt(max_depth=2, min_child_samples=30).fit(train.query(f"{T} == 0")[X], d_train[train[T] == 0])
mx1 = lt(max_depth=2, min_child_samples=30).fit(train.query(f"{T} == 1")[X], d_train[train[T] == 1])
propensity = g.predict_proba(test[X])
x_cate = test.assign(cate=propensity[:, 1] * mx0.predict(test[X]) + propensity[:, 0] * mx1.predict(test[X]))

frames = {"s": s_cate, "t": t_cate, "x": x_cate}


def gain_curve(frame):
    ordered = frame.sort_values("cate", ascending=False).reset_index(drop=True)
    rows = list(range(50, len(ordered), len(ordered) // 100)) + [len(ordered)]
    effects = [
        ordered.head(row).query(f"{T} == 1")[y].mean()
        - ordered.head(row).query(f"{T} == 0")[y].mean()
        for row in rows
    ]
    gain = [effects[i] * rows[i] / len(ordered) for i in range(len(rows))]
    return {
        "x": [round(row / len(ordered), 5) for row in rows],
        "gain": [round(value, 6) for value in gain],
    }


curves = {key: gain_curve(frame) for key, frame in frames.items()}
ate = float(
    test.query(f"{T} == 1")[y].mean() - test.query(f"{T} == 0")[y].mean()
)

payload = {
    "nTrain": int(len(train)),
    "nTest": int(len(test)),
    "trainRate": round(float(train[T].mean()), 5),
    "testRate": round(float(test[T].mean()), 5),
    "ate": round(ate, 6),
    "curves": curves,
    "top10": {key: curves[key]["gain"][10] for key in curves},
    "cate": {
        key: {
            "min": round(float(frame.cate.min()), 5),
            "max": round(float(frame.cate.max()), 5),
            "mean": round(float(frame.cate.mean()), 5),
        }
        for key, frame in frames.items()
    },
}
js = "/* Generated by tools/build-ch21-data.py from invest_email_biased/rnd. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch21Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("ate", payload["ate"], "top10", payload["top10"], "cate", payload["cate"])
