"""Generate assets/js/data-ch20.js for the target-transformation gain labs."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from lightgbm import LGBMRegressor

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch20.js"

# binary email
email = pd.read_csv(BASE / "invest_email_rnd.csv")
rng = np.random.RandomState(123)
perm = rng.permutation(len(email))
email_test = email.iloc[perm[:6000]].copy()
email_train = email.iloc[perm[6000:]].copy()

X = ["age", "income", "insurance", "invested"]
T = "em1"
Y = "converted"
ps = email_train[T].mean()
y_star = email_train[Y] * (email_train[T] - ps) / (ps * (1 - ps))
binary_model = LGBMRegressor(
    max_depth=3, min_child_samples=300, num_leaves=5, random_state=123, verbose=-1
)
binary_model.fit(email_train[X], y_star)


def binary_gain(df):
    data = df.assign(cate=binary_model.predict(df[X])).sort_values("cate", ascending=False).reset_index(drop=True)
    rows = list(range(50, len(data), len(data) // 100)) + [len(data)]
    effects = [
        data.head(row).query(f"{T} == 1")[Y].mean() - data.head(row).query(f"{T} == 0")[Y].mean()
        for row in rows
    ]
    gain = [effects[i] * rows[i] / len(data) for i in range(len(rows))]
    return {
        "x": [round(row / len(data), 5) for row in rows],
        "gain": [round(value, 6) for value in gain],
        "ate": round(float(data.query(f"{T} == 1")[Y].mean() - data.query(f"{T} == 0")[Y].mean()), 6),
    }


binary_train = binary_gain(email_train)
binary_test = binary_gain(email_test)
binary_cate = binary_model.predict(email_test[X])

# continuous prices
prices = pd.read_csv(BASE / "ice_cream_sales_rnd.csv")
rng = np.random.RandomState(123)
perm = rng.permutation(len(prices))
price_test = prices.iloc[perm[:1500]].copy()
price_train = prices.iloc[perm[1500:]].copy()
transformed = (price_train.price - price_train.price.mean()) * (
    price_train.sales - price_train.sales.mean()
)
continuous_model = LGBMRegressor(
    max_depth=3, min_child_samples=300, num_leaves=5, random_state=123, verbose=-1
)
continuous_model.fit(price_train[["temp", "weekday", "cost"]], transformed)


def continuous_slope(data):
    return float(
        np.sum((data.price - data.price.mean()) * (data.sales - data.sales.mean()))
        / np.sum((data.price - data.price.mean()) ** 2)
    )


def continuous_gain(df):
    data = df.assign(cate=continuous_model.predict(df[["temp", "weekday", "cost"]])).sort_values(
        "cate", ascending=False
    ).reset_index(drop=True)
    rows = list(range(50, len(data), len(data) // 100)) + [len(data)]
    effects = [continuous_slope(data.head(row)) for row in rows]
    gain = [effects[i] * rows[i] / len(data) for i in range(len(rows))]
    return {
        "x": [round(row / len(data), 5) for row in rows],
        "gain": [round(value, 5) for value in gain],
        "ate": round(continuous_slope(data), 5),
    }


continuous_train = continuous_gain(price_train)
continuous_test = continuous_gain(price_test)
continuous_cate = continuous_model.predict(price_test[["temp", "weekday", "cost"]])

payload = {
    "binary": {
        "n": int(len(email)),
        "nTrain": int(len(email_train)),
        "nTest": int(len(email_test)),
        "ps": round(float(ps), 8),
        "curves": {"train": binary_train, "test": binary_test},
        "top10": {"train": binary_train["gain"][10], "test": binary_test["gain"][10]},
        "cate": {
            "min": round(float(binary_cate.min()), 6),
            "max": round(float(binary_cate.max()), 6),
            "mean": round(float(binary_cate.mean()), 6),
        },
    },
    "continuous": {
        "n": int(len(prices)),
        "nTrain": int(len(price_train)),
        "nTest": int(len(price_test)),
        "curves": {"train": continuous_train, "test": continuous_test},
        "top10": {"train": continuous_train["gain"][10], "test": continuous_test["gain"][10]},
        "cate": {
            "min": round(float(continuous_cate.min()), 4),
            "max": round(float(continuous_cate.max()), 4),
            "mean": round(float(continuous_cate.mean()), 4),
        },
    },
}

js = "/* Generated by tools/build-ch20-data.py from invest_email_rnd and ice_cream_sales_rnd. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch20Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("binary", payload["binary"]["top10"], payload["binary"]["cate"])
print("continuous", payload["continuous"]["top10"], payload["continuous"]["cate"])
