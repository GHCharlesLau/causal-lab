"""Generate assets/js/data-ch19.js for the cumulative gain lab."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.ensemble import GradientBoostingRegressor

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch19.js"

prices = pd.read_csv(BASE / "ice_cream_sales.csv")
rnd = pd.read_csv(BASE / "ice_cream_sales_rnd.csv")
X = ["temp", "weekday", "cost", "price"]
weekdays = sorted(prices.weekday.unique())


def design(frame, price_shift=0.0):
    price = frame.price.values + price_shift
    cols = [np.ones(len(frame)), price, frame.temp.values, frame.cost.values]
    for wd in weekdays[1:]:
        cols.append((frame.weekday.values == wd).astype(float))
    cols += [price * frame.cost.values, price * frame.temp.values]
    for wd in weekdays[1:]:
        cols.append(price * (frame.weekday.values == wd))
    return np.column_stack(cols)


beta = np.linalg.lstsq(design(prices), prices.sales.values, rcond=None)[0]
sensitivity = (design(rnd, 0.01) @ beta - design(rnd) @ beta) / 0.01

np.random.seed(1)
ml = GradientBoostingRegressor()
ml.fit(prices[X], prices.sales)
np.random.seed(123)
random_score = np.random.uniform(size=len(rnd))

frame = rnd.assign(sens=sensitivity, pred=ml.predict(rnd[X]), rand=random_score)


def slope(data):
    return float(
        np.sum((data.price - data.price.mean()) * (data.sales - data.sales.mean()))
        / np.sum((data.price - data.price.mean()) ** 2)
    )


def curve(column):
    ordered = frame.sort_values(column, ascending=False).reset_index(drop=True)
    rows = list(range(50, len(frame), len(frame) // 100)) + [len(frame)]
    sens = [slope(ordered.head(row)) for row in rows]
    gain = [sens[i] * rows[i] / len(frame) for i in range(len(rows))]
    return {
        "x": [round(row / len(frame), 5) for row in rows],
        "sensitivity": [round(value, 5) for value in sens],
        "gain": [round(value, 5) for value in gain],
    }


curves = {
    "causal": curve("sens"),
    "predictive": curve("pred"),
    "random": curve("rand"),
}


def band_slopes(column):
    bands = pd.qcut(frame[column], 10, labels=False)
    return [round(slope(frame[bands == i]), 4) for i in range(10)]


payload = {
    "n": int(len(frame)),
    "ate": round(slope(frame), 6),
    "r2": {
        "train": round(float(ml.score(prices[X], prices.sales)), 8),
        "test": round(float(ml.score(rnd[X], rnd.sales)), 8),
    },
    "curves": curves,
    "topGain": {
        key: round(value["gain"][25], 5) for key, value in curves.items()
    },
    "bands": {
        "causal": band_slopes("sens"),
        "predictive": band_slopes("pred"),
        "random": band_slopes("rand"),
    },
}
js = "/* Generated by tools/build-ch19-data.py from ice_cream_sales*.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch19Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("ate", payload["ate"], "r2", payload["r2"], "topGain", payload["topGain"])
print("bands causal", payload["bands"]["causal"])
