"""Generate assets/js/data-ch13.js from billboard_impact.csv."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "billboard_impact.csv"
OUT = ROOT / "assets" / "js" / "data-ch13.js"

df = pd.read_csv(SRC)
means = df.groupby(["poa", "jul"])["deposits"].mean()
counts = df.groupby(["poa", "jul"])["deposits"].count()

X = np.column_stack([np.ones(len(df)), df.poa, df.jul, df.poa * df.jul])
y = df.deposits.values
beta = np.linalg.inv(X.T @ X) @ X.T @ y
resid = y - X @ beta
sigma2 = resid @ resid / (len(df) - X.shape[1])
se = np.sqrt(np.diag(sigma2 * np.linalg.inv(X.T @ X)))

payload = {
    "n": int(len(df)),
    "means": {
        "flBefore": round(float(means.loc[(0, 0)]), 8),
        "flAfter": round(float(means.loc[(0, 1)]), 8),
        "poaBefore": round(float(means.loc[(1, 0)]), 8),
        "poaAfter": round(float(means.loc[(1, 1)]), 8),
    },
    "counts": {
        "flBefore": int(counts.loc[(0, 0)]),
        "flAfter": int(counts.loc[(0, 1)]),
        "poaBefore": int(counts.loc[(1, 0)]),
        "poaAfter": int(counts.loc[(1, 1)]),
    },
    "beforeAfter": round(float(means.loc[(1, 1)] - means.loc[(1, 0)]), 8),
    "crossSection": round(float(means.loc[(1, 1)] - means.loc[(0, 1)]), 8),
    "did": round(float((means.loc[(1, 1)] - means.loc[(1, 0)]) - (means.loc[(0, 1)] - means.loc[(0, 0)])), 8),
    "ols": {
        "intercept": round(float(beta[0]), 8),
        "poa": round(float(beta[1]), 8),
        "jul": round(float(beta[2]), 8),
        "interaction": round(float(beta[3]), 8),
        "seInteraction": round(float(se[3]), 8),
        "lo": round(float(beta[3] - 1.96 * se[3]), 6),
        "hi": round(float(beta[3] + 1.96 * se[3]), 6),
    },
}
js = "/* Generated by tools/build-ch13-data.py from billboard_impact.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch13Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes, n={len(df)})")
print(payload)
