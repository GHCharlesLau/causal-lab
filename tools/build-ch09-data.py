"""Generate assets/js/data-ch09.js from the book's app_engagement_push.csv."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "app_engagement_push.csv"
OUT = ROOT / "assets" / "js" / "data-ch09.js"

df = pd.read_csv(SRC)
tab = pd.crosstab(df["push_assigned"], df["push_delivered"])
counts = {
    "assigned0_delivered0": int(tab.loc[0, 0]),
    "assigned0_delivered1": int(tab.loc[0, 1]),
    "assigned1_delivered0": int(tab.loc[1, 0]),
    "assigned1_delivered1": int(tab.loc[1, 1]),
}
means = {
    "assigned0": float(df.loc[df.push_assigned == 0, "in_app_purchase"].mean()),
    "assigned1": float(df.loc[df.push_assigned == 1, "in_app_purchase"].mean()),
    "delivered0": float(df.loc[df.push_delivered == 0, "in_app_purchase"].mean()),
    "delivered1": float(df.loc[df.push_delivered == 1, "in_app_purchase"].mean()),
}
payload = {
    "n": int(len(df)),
    "assigned": int(df.push_assigned.sum()),
    "delivered": int(df.push_delivered.sum()),
    "counts": counts,
    "means": {k: round(v, 8) for k, v in means.items()},
    "delivery_rate_assigned": round(float(df.loc[df.push_assigned == 1, "push_delivered"].mean()), 8),
    "delivery_rate_unassigned": round(float(df.loc[df.push_assigned == 0, "push_delivered"].mean()), 8),
}
js = "/* Generated by tools/build-ch09-data.py from app_engagement_push.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch09Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes, n={len(df)})")
print(counts)
print(payload["delivery_rate_assigned"])
