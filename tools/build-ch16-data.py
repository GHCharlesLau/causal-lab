"""Generate assets/js/data-ch16.js for the sharp and fuzzy RD labs."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch16.js"


def wls(df, y, x, t, weights=None):
    X = np.column_stack([np.ones(len(df)), df[x].values, df[t].values, df[x].values * df[t].values])
    yy = df[y].values
    w = np.ones(len(df)) if weights is None else np.asarray(weights, dtype=float)
    return np.linalg.solve(X.T @ (w[:, None] * X), X.T @ (w * yy))


drinking = pd.read_csv(BASE / "drinking.csv")
drinking["agecell"] -= 21
drinking["threshold"] = (drinking["agecell"] > 0).astype(int)
drinking = drinking.dropna(subset=["all", "mva", "suicide"]).copy()
kernel = np.where(np.abs(drinking["agecell"]) <= 1, 1 - np.abs(drinking["agecell"]) / 1, 0)

sharp = {}
for outcome in ["all", "mva", "suicide"]:
    full = wls(drinking, outcome, "agecell", "threshold")
    local = wls(drinking, outcome, "agecell", "threshold", kernel)
    sharp[outcome] = {
        "full": {
            "intercept": round(float(full[0]), 8),
            "slope": round(float(full[1]), 8),
            "jump": round(float(full[2]), 8),
            "interaction": round(float(full[3]), 8),
            "pct": round(float(100 * ((full[2] + full[0]) / full[0] - 1)), 4),
        },
        "local": {
            "intercept": round(float(local[0]), 8),
            "slope": round(float(local[1]), 8),
            "jump": round(float(local[2]), 8),
            "interaction": round(float(local[3]), 8),
            "pct": round(float(100 * ((local[2] + local[0]) / local[0] - 1)), 4),
        },
    }

sheep = pd.read_csv(BASE / "sheepskin.csv")[["avgearnings", "minscore", "receivehsd", "n"]].copy()
sheep["threshold"] = (sheep["minscore"] > 0).astype(int)
sheep_weights = np.where(np.abs(sheep["minscore"]) <= 15, 1 - np.abs(sheep["minscore"]) / 15, 0) * sheep["n"].values
num = wls(sheep, "avgearnings", "minscore", "threshold", sheep_weights)
den = wls(sheep, "receivehsd", "minscore", "threshold", sheep_weights)
wald = num[2] / den[2]

payload = {
    "drinking": {
        "rows": [
            {
                "age": round(float(row.agecell), 6),
                "all": round(float(row.all), 6),
                "mva": round(float(row.mva), 6),
                "suicide": round(float(row.suicide), 6),
            }
            for row in drinking.itertuples(index=False)
        ],
        "n": int(len(drinking)),
        "sharp": sharp,
    },
    "sheepskin": {
        "earningsCoef": [round(float(x), 8) for x in num],
        "firstCoef": [round(float(x), 8) for x in den],
        "rows": [
            {
                "score": float(row.minscore),
                "earnings": round(float(row.avgearnings), 4),
                "diploma": round(float(row.receivehsd), 6),
                "n": int(row.n),
            }
            for row in sheep.itertuples(index=False)
        ],
        "n": int(len(sheep)),
        "numerator": round(float(num[2]), 6),
        "denominator": round(float(den[2]), 6),
        "wald": round(float(wald), 4),
        "ci": [-3235.1543, 1383.3578],
    },
}
js = "/* Generated by tools/build-ch16-data.py from drinking.csv and sheepskin.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch16Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("sharp", sharp)
print("fuzzy", payload["sheepskin"]["numerator"], payload["sheepskin"]["denominator"], payload["sheepskin"]["wald"])
