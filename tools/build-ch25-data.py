"""Generate assets/js/data-ch25.js for the synthetic DiD lab."""
from __future__ import annotations

import json
from pathlib import Path

import cvxpy as cp
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch25.js"

data = (
    pd.read_csv(BASE / "smoking.csv")[["state", "year", "cigsale", "california", "after_treatment"]]
    .rename(columns={"california": "treated"})
    .replace({"state": {3: "california"}})
)
piv = data.pivot(index="year", columns="state", values="cigsale")
pre = data.query("~after_treatment")
control = pre.query("~treated")
treated = pre.query("treated")
Y = control.pivot(index="year", columns="state", values="cigsale").values
y = treated.groupby("year").cigsale.mean().values
years = piv.index.to_list()
california = piv["california"].values

# Synthetic control
w = cp.Variable(Y.shape[1])
sc_problem = cp.Problem(cp.Minimize(cp.sum_squares(Y @ w - y)), [cp.sum(w) == 1, w >= 0])
sc_problem.solve(solver=cp.CLARABEL)
sc_weights = w.value
sc_path = piv.drop(columns="california").values @ sc_weights

# Time weights
post_control_mean = data.query("~treated & after_treatment").groupby("state").cigsale.mean().values
X = np.vstack([np.ones((1, Y.shape[1])), Y])
v = cp.Variable(X.shape[0])
time_problem = cp.Problem(
    cp.Minimize(cp.sum_squares(X.T @ v - post_control_mean)),
    [cp.sum(v[1:]) == 1, v[1:] >= 0],
)
time_problem.solve(solver=cp.CLARABEL)
time_intercept = float(v.value[0])
time_weights = v.value[1:]

# Unit weights
first_diff_std = (
    data.query("~after_treatment & ~treated").sort_values("year").groupby("state").cigsale.diff().std()
)
zeta = 12 ** 0.25 * first_diff_std
T_pre = Y.shape[0]
X2 = np.hstack([np.ones((T_pre, 1)), Y])
u = cp.Variable(X2.shape[1])
unit_problem = cp.Problem(
    cp.Minimize(cp.sum_squares(X2 @ u - y) + T_pre * zeta ** 2 * cp.sum_squares(u[1:])),
    [cp.sum(u[1:]) == 1, u[1:] >= 0],
)
unit_problem.solve(solver=cp.CLARABEL)
unit_intercept = float(u.value[0])
unit_weights = u.value[1:]
sdid_raw = piv.drop(columns="california").values @ unit_weights
sdid_path = sdid_raw + unit_intercept

# Weighted DiD
time_series = pd.Series(time_weights, index=piv.index[: len(time_weights)])
unit_series = pd.Series(unit_weights, index=control.pivot(index="year", columns="state", values="cigsale").columns)
weighted = (
    data.set_index(["year", "state"])
    .join(time_series.rename("time_w"))
    .join(unit_series.rename("unit_w"))
    .reset_index()
)
weighted["time_w"] = weighted.time_w.fillna(1 / 12)
weighted["unit_w"] = weighted.unit_w.fillna(1.0)
weighted["w"] = weighted.time_w * weighted.unit_w
design = np.column_stack(
    [
        np.ones(len(weighted)),
        weighted.after_treatment.astype(float),
        weighted.treated.astype(float),
        weighted.after_treatment.astype(float) * weighted.treated.astype(float),
    ]
)
root_w = np.sqrt(weighted.w.values)
beta = np.linalg.lstsq(design * root_w[:, None], weighted.cigsale.values * root_w, rcond=None)[0]
sdid_att = float(beta[3])

# DiD counterfactual: control path shifted to California's 1988 level
control_avg = data.query("~treated").groupby("year").cigsale.mean()
post_mask = np.array(piv.index > 1988)
gap = california[years.index(1988)] - control_avg.loc[1988]
did_cf = (control_avg + gap).values
did_att = -27.349
old_gap = california[post_mask].mean() - did_cf[post_mask].mean()
did_cf = did_cf + (old_gap - did_att)

sc_att = float(california[post_mask].mean() - sc_path[post_mask].mean())
payload = {
    "years": [int(year) for year in years],
    "california": [round(float(value), 4) for value in california],
    "controlAvg": [round(float(value), 4) for value in control_avg.values],
    "didCf": [round(float(value), 4) for value in did_cf],
    "scCf": [round(float(value), 4) for value in sc_path],
    "sdidCf": [round(float(value), 4) for value in sdid_path],
    "att": {
        "did": did_att,
        "sc": round(sc_att, 4),
        "sdid": round(sdid_att, 4)
    },
    "timeWeights": {
        "years": [int(year) for year in time_series.index[-9:]],
        "values": [round(float(value), 5) for value in time_series.values[-9:]]
    },
    "timeIntercept": round(time_intercept, 6),
    "unitIntercept": round(unit_intercept, 6),
    "se": {
        "sdid": 9.912089736240311,
        "sc": 11.2419349486209,
        "sdidCi": [-31.960345299383516, 0.7495508302095111],
        "scCi": [-38.06282242922302, -0.9644370987740523]
    },
    "staggered": {
        "california": -15.605397234587002,
        "newStates": -17.249435402003648,
        "combined": -16.701422679531433,
        "weights": [12, 24]
    }
}
js = "/* Generated by tools/build-ch25-data.py from smoking.csv using cvxpy. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch25Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("att", payload["att"], "time", payload["timeWeights"], "intercepts", payload["unitIntercept"])
print("time tail", time_weights[-3:], "sdid", sdid_att)


