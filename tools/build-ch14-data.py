"""Generate assets/js/data-ch14.js from the wage panel and the book's toy panel."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "reference" / "data" / "wage_panel.csv"
OUT = ROOT / "assets" / "js" / "data-ch14.js"

df = pd.read_csv(SRC)

toy = pd.DataFrame(
    {
        "cost": [5, 4, 3.5, 3, 10, 9.5, 9, 8, 4, 3, 2, 1, 8, 7, 6, 4],
        "purchase": [12, 9, 7.5, 7, 9, 7, 6.5, 5, 15, 14.5, 14, 13, 11, 9.5, 8, 5],
        "city": ["C0"] * 4 + ["C2"] * 4 + ["C1"] * 4 + ["C3"] * 4,
    }
)

X = np.column_stack([np.ones(len(toy)), toy.cost])
pooled = np.linalg.lstsq(X, toy.purchase.values, rcond=None)[0]
D = pd.get_dummies(toy.city, drop_first=True, dtype=float)
Xf = np.column_stack([np.ones(len(toy)), toy.cost, D.values])
fe = np.linalg.lstsq(Xf, toy.purchase.values, rcond=None)[0]

payload = {
    "n": int(len(df)),
    "entities": int(df.nr.nunique()),
    "years": int(df.year.nunique()),
    "toy": {
        "rows": [
            {"cost": float(row.cost), "purchase": float(row.purchase), "city": row.city}
            for row in toy.itertuples(index=False)
        ],
        "pooledSlope": round(float(pooled[1]), 8),
        "feSlope": round(float(fe[1]), 8),
    },
    "yearMeans": {
        str(int(year)): round(float(value), 8)
        for year, value in df.groupby("year")["lwage"].mean().items()
    },
}
js = "/* Generated by tools/build-ch14-data.py from the wage panel and toy panel. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch14Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes, n={len(df)})")
print("toy pooled", pooled[1], "fe", fe[1])
