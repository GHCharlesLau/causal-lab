"""Generate assets/js/data-a4.js for the prediction-metrics note."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "js" / "data-a4.js"

n = 100000
n_features = 20
n_heter = 10
np.random.seed(12321)
X = np.random.normal(1, 10, (n, n_features))
nuisance = np.random.uniform(-1, 1, (n_features, 1))
W = np.random.normal(1, 10, (n, n_heter))
heter_y = np.random.uniform(-1, 1, (n_heter, 1))
T = np.random.normal(10, 2, (n, 1))
Y = np.random.normal(T + T * W.dot(heter_y) + 20 * X.dot(nuisance), 0.1)

perm = np.random.permutation(n)
test_idx = perm[: n // 2]
train_idx = perm[n // 2:]


def design(frame_X, frame_W, t, interactions=True):
    base = [np.ones(len(t)), t]
    base += [frame_X[:, i] for i in range(frame_X.shape[1])]
    base += [frame_W[:, i] for i in range(frame_W.shape[1])]
    if interactions:
        base += [t * frame_X[:, i] for i in range(frame_X.shape[1])]
        base += [t * frame_W[:, i] for i in range(frame_W.shape[1])]
    return np.column_stack(base)


def fit(frame_X, frame_W, t, y):
    return np.linalg.lstsq(design(frame_X, frame_W, t), y, rcond=None)[0]


def predict(beta, frame_X, frame_W, t):
    return design(frame_X, frame_W, t) @ beta


def r2(y, pred):
    return float(1 - ((y - pred) ** 2).sum() / ((y - y.mean()) ** 2).sum())


t = T[:, 0]
y = Y[:, 0]

# m1: nuisance features only
X1 = np.hstack([X, np.zeros((n, n_heter))])
beta1 = fit(X1, np.zeros((n, n_heter)), t, y)
# m2: heterogeneity features only
X2 = np.hstack([np.zeros((n, n_features)), W])
beta2 = fit(X2, W, t, y)

pred1 = predict(beta1, X1, np.zeros((n, n_heter)), t)
pred2 = predict(beta2, X2, W, t)
cate1 = predict(beta1, X1, np.zeros((n, n_heter)), t) - predict(beta1, X1, np.zeros((n, n_heter)), t - 1)
cate2 = predict(beta2, X2, W, t) - predict(beta2, X2, W, t - 1)

test = test_idx
y_test = y[test]
r2_m1 = r2(y_test, pred1[test])
r2_m2 = r2(y_test, pred2[test])


def slope(yy, tt):
    tm = tt.mean()
    ym = yy.mean()
    return float(((tt - tm) * (yy - ym)).sum() / ((tt - tm) ** 2).sum())


def curve(cate):
    order = np.argsort(-cate[test])
    rows = list(range(50, len(test), len(test) // 100)) + [len(test)]
    gains = []
    for row in rows:
        idx = test[order[:row]]
        gains.append(slope(y[idx], t[idx]) * row / len(test))
    return {
        "x": [round(row / len(test), 5) for row in rows],
        "gain": [round(value, 5) for value in gains],
    }


curve1 = curve(cate1)
curve2 = curve(cate2)

# denoise model on train
train = train_idx
X_train = np.column_stack([X[train], W[train]])
beta_y = np.linalg.lstsq(np.column_stack([np.ones(len(train)), X_train]), y[train], rcond=None)[0]
denoised = np.column_stack([np.ones(len(test)), X[test], W[test]]) @ beta_y
y_res = y_test - denoised + y.mean()
r2_res1 = r2(y_res, pred1[test])
r2_res2 = r2(y_res, pred2[test])

payload = {
    "n": n,
    "nTest": int(len(test)),
    "r2": {"m1": round(r2_m1, 8), "m2": round(r2_m2, 8)},
    "r2Res": {"m1": round(r2_res1, 4), "m2": round(r2_res2, 4)},
    "curves": {"m1": curve1, "m2": curve2},
    "end": {"m1": round(curve1["gain"][-1], 5), "m2": round(curve2["gain"][-1], 5)},
    "cate": {
        "m1": {"min": round(float(cate1.min()), 4), "max": round(float(cate1.max()), 4)},
        "m2": {"min": round(float(cate2.min()), 4), "max": round(float(cate2.max()), 4)}
    }
}
js = "/* Generated by tools/build-a4-data.py; simulated with seed 12321. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.A4Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("r2", payload["r2"], "r2res", payload["r2Res"], "end", payload["end"])
