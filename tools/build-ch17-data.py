"""Generate assets/js/data-ch17.js for the profitability policy lab."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch17.js"

transactions = pd.read_csv(BASE / "customer_transactions.csv")
features = pd.read_csv(BASE / "customer_features.csv")
net_value = transactions.drop(columns="customer_id").sum(axis=1)
customer = features.merge(
    pd.DataFrame({"customer_id": transactions.customer_id, "net_value": net_value}),
    on="customer_id",
)

rng = np.random.RandomState(13)
perm = rng.permutation(len(customer))
test = customer.iloc[perm[:3000]].copy()
train = customer.iloc[perm[3000:]].copy()

region = train.groupby("region")["net_value"].agg(["mean", "count", "std"])
region["lower"] = region["mean"] - 1.96 * region["std"] / np.sqrt(region["count"])
test_region = test.groupby("region")["net_value"].agg(["sum", "count"])

rows = []
for region_id in sorted(region.index):
    rows.append(
        {
            "region": int(region_id),
            "mean": round(float(region.loc[region_id, "mean"]), 6),
            "lower": round(float(region.loc[region_id, "lower"]), 6),
            "count": int(region.loc[region_id, "count"]),
            "testSum": round(float(test_region.loc[region_id, "sum"]), 6) if region_id in test_region.index else 0.0,
            "testCount": int(test_region.loc[region_id, "count"]) if region_id in test_region.index else 0,
        }
    )

selected_zero = [row for row in rows if row["lower"] > 0]
test_sum_zero = sum(row["testSum"] for row in selected_zero)
payload = {
    "n": int(len(customer)),
    "nTest": int(len(test)),
    "trainMean": round(float(train["net_value"].mean()), 8),
    "testMean": round(float(test["net_value"].mean()), 8),
    "treatAllTest": round(float(test["net_value"].mean()), 8),
    "regions": rows,
    "selectedAtZero": len(selected_zero),
    "policyAtZero": round(float(test_sum_zero / len(test)), 6),
    "modelPolicy": 16.6,
    "trainR2": 0.7108790300152951,
    "testR2": 0.6938513063048141,
}
js = "/* Generated by tools/build-ch17-data.py from the customer files. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch17Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("train/test mean", payload["trainMean"], payload["testMean"])
print("selected", payload["selectedAtZero"], "policy", payload["policyAtZero"])
