"""Generate assets/js/data-ch24.js for the DiD saga lab."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "js" / "data-ch24.js"


def twfe(frame, treat="treat", outcome="installs", unit="unit", date="date"):
    units = sorted(frame[unit].unique())
    dates = sorted(frame[date].unique())
    cols = [frame[treat].values.astype(float), np.ones(len(frame))]
    names = ["treat", "intercept"]
    for value in units[1:]:
        cols.append((frame[unit].values == value).astype(float))
        names.append("u" + str(value))
    for value in dates[1:]:
        cols.append((frame[date].values == value).astype(float))
        names.append("d" + str(value))
    design = np.column_stack(cols)
    beta = np.linalg.lstsq(design, frame[outcome].values, rcond=None)[0]
    return float(beta[0])


def cohort_series(frame):
    grouped = frame.groupby(["cohort", "date"])["installs"].mean().reset_index()
    dates = sorted(grouped.date.unique())
    series = {}
    for cohort in sorted(grouped.cohort.unique()):
        part = grouped[grouped.cohort == cohort].set_index("date")
        series[str(cohort)] = [round(float(part.loc[date, "installs"]), 3) for date in dates]
    return [str(date) for date in dates], series


def summary(frame):
    dates, series = cohort_series(frame)
    return {
        "dates": dates,
        "series": series,
        "twfe": round(twfe(frame), 6),
        "true": round(float(frame.loc[frame.treat == 1, "tau"].mean()), 6),
    }


date = pd.date_range("2021-05-01", "2021-07-31", freq="D")
cohorts = pd.to_datetime(["2021-06-01", "2021-07-15", "2022-01-01"]).date
units = range(1, 100 + 1)
np.random.seed(1)
base = pd.DataFrame(
    {
        "date": np.tile(date, len(units)),
        "unit": np.repeat(units, len(date)),
        "cohort": np.repeat(np.random.choice(cohorts, len(units)), len(date)),
        "unit_fe": np.repeat(np.random.normal(0, 5, size=len(units)), len(date)),
        "time_fe": np.tile(np.random.normal(size=len(date)), len(units)),
        "week_day": np.tile(date.weekday, len(units)),
        "w_seas": np.tile(abs(5 - date.weekday) % 7, len(units)),
    }
).assign(
    trend=lambda d: (d["date"] - d["date"].min()).dt.days / 70,
    day=lambda d: (d["date"] - d["date"].min()).dt.days,
    treat=lambda d: (d["date"] >= d["cohort"]).astype(int),
)
constant = (
    base.assign(y0=lambda d: 10 + d["trend"] + d["unit_fe"] + 0.1 * d["time_fe"] + d["w_seas"] / 10)
    .assign(y1=lambda d: d["y0"] + 1)
    .assign(tau=lambda d: d["y1"] - d["y0"], installs=lambda d: np.where(d["treat"] == 1, d["y1"], d["y0"]))
)
mature = (
    base.assign(
        y0=lambda d: 10 + d["trend"] + 0.2 * d["unit_fe"] + 0.05 * d["time_fe"] + d["w_seas"] / 50
    )
    .assign(
        y1=lambda d: d["y0"]
        + np.minimum(0.1 * (np.maximum(0, (d["date"] - pd.to_datetime(d["cohort"])).dt.days)), 1)
    )
    .assign(tau=lambda d: d["y1"] - d["y0"], installs=lambda d: np.where(d["treat"] == 1, d["y1"], d["y0"]))
)

date_min = pd.date_range("2021-05-15", "2021-07-01", freq="D")
cohorts_min = pd.to_datetime(["2021-06-01", "2021-06-15"]).date
np.random.seed(1)
minimal = pd.DataFrame(
    {
        "date": np.tile(date_min, len(units)),
        "unit": np.repeat(units, len(date_min)),
        "cohort": np.repeat(np.random.choice(cohorts_min, len(units)), len(date_min)),
        "unit_fe": np.repeat(np.random.normal(0, 5, size=len(units)), len(date_min)),
    }
).assign(
    trend=0,
    day=lambda d: (d["date"] - d["date"].min()).dt.days,
    treat=lambda d: (d["date"] >= d["cohort"]).astype(int),
).assign(
    y0=lambda d: 10 - d["trend"] + 0.1 * d["unit_fe"]
).assign(
    y1=lambda d: d["y0"] - 0.1 * (np.maximum(0, (d["date"] - pd.to_datetime(d["cohort"])).dt.days))
).assign(
    tau=lambda d: d["y1"] - d["y0"],
    installs=lambda d: np.where(d["treat"] == 1, d["y1"], d["y0"]),
)

payload = {
    "constant": summary(constant),
    "mature": summary(mature),
    "minimal": summary(minimal),
    "fix": {
        "true": 0.8544117647058823,
        "flexible": 0.8544117647058977,
        "params": 467,
        "reducedParams": 271,
        "reduced": 0.8544117647059067,
    },
}
js = "/* Generated by tools/build-ch24-data.py; simulated with seed 1. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch24Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
for key in ["constant", "mature", "minimal"]:
    print(key, payload[key]["twfe"], payload[key]["true"])

