"""Generate assets/js/data-ch22.js for orthogonal ML residual and gain labs."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from lightgbm import LGBMRegressor
from sklearn.model_selection import cross_val_predict

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch22.js"

train = pd.read_csv(BASE / "ice_cream_sales.csv")
test = pd.read_csv(BASE / "ice_cream_sales_rnd.csv")
y = "sales"
T = "price"
X = ["temp", "weekday", "cost"]
weekdays = sorted(train.weekday.unique())


def ols_design(frame):
    cols = [np.ones(len(frame)), frame.price.values, frame.temp.values, frame.cost.values]
    for wd in weekdays[1:]:
        cols.append((frame.weekday.values == wd).astype(float))
    return np.column_stack(cols)


_ = np.linalg.lstsq(ols_design(train), train.sales.values, rcond=None)[0]
raw_slope = float(np.polyfit(train.price, train.sales, 1)[0])

debias = LGBMRegressor(max_depth=3, random_state=123, verbose=-1)
denoise = LGBMRegressor(max_depth=3, random_state=123, verbose=-1)
price_pred = cross_val_predict(debias, train[X], train[T], cv=5)
sales_pred = cross_val_predict(denoise, train[X], train[y], cv=5)
residuals = train.assign(
    price_res=train[T] - price_pred,
    sales_res=train[y] - sales_pred,
)
residual_slope = float(
    np.sum(residuals.price_res * residuals.sales_res)
    / np.sum(residuals.price_res ** 2)
)


def cate_design(frame, price_res):
    cols = [np.ones(len(frame)), price_res, frame.temp.values, frame.cost.values]
    for wd in weekdays[1:]:
        cols.append((frame.weekday.values == wd).astype(float))
    cols += [price_res * frame.temp.values, price_res * frame.cost.values]
    for wd in weekdays[1:]:
        cols.append(price_res * (frame.weekday.values == wd))
    return np.column_stack(cols)


beta = np.linalg.lstsq(
    cate_design(residuals, residuals.price_res.values),
    residuals.sales_res.values,
    rcond=None,
)[0]
param_cate = (
    cate_design(test, np.ones(len(test))) @ beta
    - cate_design(test, np.zeros(len(test))) @ beta
)

weights = residuals.price_res ** 2
target = residuals.sales_res / residuals.price_res
np.random.seed(123)
nonparam_model = LGBMRegressor(max_depth=3, random_state=123, verbose=-1)
nonparam_model.fit(train[X], target, sample_weight=weights)
nonparam_cate = nonparam_model.predict(test[X])


def slope(data):
    return float(
        np.sum((data.price - data.price.mean()) * (data.sales - data.sales.mean()))
        / np.sum((data.price - data.price.mean()) ** 2)
    )


def gain_curve(cate):
    frame = test.assign(cate=cate).sort_values("cate", ascending=False).reset_index(drop=True)
    rows = list(range(50, len(frame), len(frame) // 100)) + [len(frame)]
    effects = [slope(frame.head(row)) for row in rows]
    gains = [effects[i] * rows[i] / len(frame) for i in range(len(rows))]
    return {
        "x": [round(row / len(frame), 5) for row in rows],
        "gain": [round(value, 5) for value in gains],
    }


param_curve = gain_curve(param_cate)
nonparam_curve = gain_curve(nonparam_cate)
sample = residuals.sample(600, random_state=123)

payload = {
    "nTrain": int(len(train)),
    "nTest": int(len(test)),
    "rawSlope": round(raw_slope, 6),
    "olsSlope": -4.00042915,
    "residualSlope": round(residual_slope, 6),
    "testAte": round(slope(test), 6),
    "top10": {
        "param": param_curve["gain"][10],
        "nonparam": nonparam_curve["gain"][10],
    },
    "curves": {"param": param_curve, "nonparam": nonparam_curve},
    "cate": {
        "param": {
            "min": round(float(param_cate.min()), 5),
            "max": round(float(param_cate.max()), 5),
            "mean": round(float(param_cate.mean()), 5),
        },
        "nonparam": {
            "min": round(float(nonparam_cate.min()), 5),
            "max": round(float(nonparam_cate.max()), 5),
            "mean": round(float(nonparam_cate.mean()), 5),
        },
    },
    "scatter": [
        {
            "price": round(float(row.price), 2),
            "sales": int(row.sales),
            "priceRes": round(float(row.price_res), 4),
            "salesRes": round(float(row.sales_res), 4),
        }
        for row in sample.itertuples()
    ],
}
js = "/* Generated by tools/build-ch22-data.py from ice_cream_sales*.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch22Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("raw", payload["rawSlope"], "resid", payload["residualSlope"], "test", payload["testAte"])
print("top10", payload["top10"], "cate", payload["cate"])
