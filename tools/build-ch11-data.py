"""Generate assets/js/data-ch11.js from learning_mindset.csv and a logistic propensity model."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "learning_mindset.csv"
OUT = ROOT / "assets" / "js" / "data-ch11.js"

df = pd.read_csv(SRC)
T = "intervention"
Y = "achievement_score"
categ = ["ethnicity", "gender", "school_urbanicity"]
X = pd.concat(
    [
        df.drop(columns=categ + ["schoolid", T, Y]),
        pd.get_dummies(df[categ], columns=categ, drop_first=True, dtype=float),
    ],
    axis=1,
)
X.insert(0, "intercept", 1.0)
Xv = X.values.astype(float)
y = df[T].values.astype(float)


def sigmoid(z):
    return 1 / (1 + np.exp(-np.clip(z, -30, 30)))


beta = np.zeros(Xv.shape[1])
beta[0] = np.log(y.mean() / (1 - y.mean()))
for _ in range(50):
    eta = Xv @ beta
    phat = sigmoid(eta)
    w = np.clip(phat * (1 - phat), 1e-9, None)
    z = eta + (y - phat) / w
    Xw = Xv * np.sqrt(w)[:, None]
    zw = z * np.sqrt(w)
    A = Xw.T @ Xw + 1e-8 * np.eye(Xv.shape[1])
    new_beta = np.linalg.solve(A, Xw.T @ zw)
    if np.max(np.abs(new_beta - beta)) < 1e-8:
        beta = new_beta
        break
    beta = new_beta

ps = sigmoid(Xv @ beta)
weights = (y - ps) / (ps * (1 - ps))
treated = y == 1
y1 = float(np.sum(df.loc[treated, Y].values / ps[treated]) / len(df))
y0 = float(np.sum(df.loc[~treated, Y].values / (1 - ps[~treated])) / len(df))
ate = float(np.mean(weights * df[Y].values))

rates = df.groupby("success_expect")[T].mean().sort_index()
payload = {
    "n": int(len(df)),
    "treated": int(treated.sum()),
    "control": int((~treated).sum()),
    "ps": [round(float(v), 8) for v in ps],
    "intervention": [int(v) for v in y],
    "outcome": [round(float(v), 8) for v in df[Y]],
    "success_expect": [int(v) for v in df["success_expect"]],
    "rates": {str(k): round(float(v), 8) for k, v in rates.items()},
    "y1": round(y1, 8),
    "y0": round(y0, 8),
    "ate": round(ate, 8),
    "weight_treated": round(float(np.sum(1 / ps[treated])), 6),
    "weight_control": round(float(np.sum(1 / (1 - ps[~treated]))), 6),
    "ps_treated_mean": round(float(ps[treated].mean()), 8),
    "ps_control_mean": round(float(ps[~treated].mean()), 8),
    "ps_min": round(float(ps.min()), 8),
    "ps_max": round(float(ps.max()), 8),
}
js = "/* Generated by tools/build-ch11-data.py from learning_mindset.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch11Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes, n={len(df)})")
print("ps head", ps[:5])
print("y1 y0 ate", y1, y0, ate)
print("rates", rates.to_dict())
