"""Generate assets/js/data-ch07.js from the book's two Chapter 07 datasets."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch07.js"

email = pd.read_csv(BASE / "collections_email.csv")
hospital = pd.read_csv(BASE / "hospital_treatment.csv")

payload = {
    "email": {"n": int(len(email))},
    "hospital": {"n": int(len(hospital))},
}
for col in ["payments", "email", "opened", "agreement", "credit_limit", "risk_score"]:
    payload["email"][col] = [float(x) for x in email[col]]
for col in ["hospital", "treatment", "severity", "days"]:
    payload["hospital"][col] = [float(x) for x in hospital[col]]

js = "/* Generated by tools/build-ch07-data.py from the book's collections_email.csv and hospital_treatment.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch07Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes; email={len(email)}, hospital={len(hospital)})")

