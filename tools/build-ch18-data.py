"""Generate assets/js/data-ch18.js for the CATE sensitivity bands."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "ice_cream_sales_rnd.csv"
OUT = ROOT / "assets" / "js" / "data-ch18.js"

df = pd.read_csv(SRC)

rng = np.random.RandomState(123)
perm = rng.permutation(len(df))
test = df.iloc[perm[:1250]].copy()
train = df.iloc[perm[1250:]].copy()

weekdays = sorted(df.weekday.unique())


def design(frame, with_interactions=True):
    cols = [np.ones(len(frame)), frame.price.values, frame.temp.values, frame.cost.values]
    names = ["intercept", "price", "temp", "cost"]
    for wd in weekdays[1:]:
        cols.append((frame.weekday.values == wd).astype(float))
        names.append("wd_" + str(wd))
    if with_interactions:
        cols.append(frame.price.values * frame.cost.values)
        names.append("price_cost")
        cols.append(frame.price.values * frame.temp.values)
        names.append("price_temp")
        for wd in weekdays[1:]:
            cols.append(frame.price.values * (frame.weekday.values == wd))
            names.append("price_wd_" + str(wd))
    return np.column_stack(cols), names


X, names = design(train)
beta = np.linalg.lstsq(X, train.sales.values, rcond=None)[0]
coef = dict(zip(names, beta))

m1_X = np.column_stack([np.ones(len(train)), train.price.values, train.temp.values, train.cost.values]
    + [(train.weekday.values == wd).astype(float) for wd in weekdays[1:]])
m1_beta = np.linalg.lstsq(m1_X, train.sales.values, rcond=None)[0]

# sensitivity for each test day from m3
sensitivity = np.full(len(test), coef["price"])
sensitivity += coef["price_cost"] * test.cost.values
sensitivity += coef["price_temp"] * test.temp.values
for wd in weekdays[1:]:
    sensitivity += coef["price_wd_" + str(wd)] * (test.weekday.values == wd)

median = np.median(sensitivity)
test["sens"] = sensitivity
test["band"] = np.where(sensitivity <= median, "low", "high")


def slope(frame):
    x = frame.price.values
    y = frame.sales.values
    xm = x.mean()
    ym = y.mean()
    return float(((x - xm) * (y - ym)).sum() / ((x - xm) ** 2).sum())


rows = [
    {
        "temp": round(float(row.temp), 2),
        "weekday": int(row.weekday),
        "cost": round(float(row.cost), 2),
        "price": int(row.price),
        "sales": int(row.sales),
        "sens": round(float(row.sens), 5),
        "band": row.band,
    }
    for row in test.itertuples(index=False)
]

payload = {
    "n": int(len(df)),
    "nTrain": int(len(train)),
    "nTest": int(len(test)),
    "rows": rows,
    "m1Price": round(float(m1_beta[1]), 6),
    "m2Price": -3.6299,
    "m2Interaction": 0.0366,
    "m3SensMin": round(float(sensitivity.min()), 5),
    "m3SensMax": round(float(sensitivity.max()), 5),
    "median": round(float(median), 5),
    "slopes": {
        "ate": round(slope(test), 4),
        "low": round(slope(test[test.band == "low"]), 4),
        "high": round(slope(test[test.band == "high"]), 4),
    },
    "mlR2": 0.9124088322890126,
}
js = "/* Generated by tools/build-ch18-data.py from ice_cream_sales_rnd.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch18Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("m1 price", m1_beta[1], "sens range", sensitivity.min(), sensitivity.max(), "median", median)
print("slopes", payload["slopes"])
