/* Build A5 data from the existing synthetic-control path plus the book's
   conformal confidence intervals. */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const root = path.resolve(import.meta.dirname, '..');
const ch25 = require(path.join(root, 'assets/js/data-ch25.js'));

const ci = [
  [1988, -12.323232, 8.686869],
  [1989, -16.363636, 2.222222],
  [1990, -17.171717, 5.454545],
  [1991, -19.59596, -5.858586],
  [1992, -22.828283, -7.474747],
  [1993, -32.525253, -12.323232],
  [1994, -36.565657, -15.555556],
  [1995, -43.030303, -14.747475],
  [1996, -41.414141, -16.363636],
  [1997, -48.686869, -13.131313],
  [1998, -46.262626, -13.939394],
  [1999, -46.262626, -16.363636],
  [2000, -51.111111, -17.979798]
];

const effect = ch25.california.map((value, index) => Math.round((value - ch25.scCf[index]) * 10000) / 10000);

const payload = {
  years: ch25.years,
  california: ch25.california,
  sc: ch25.scCf,
  effect,
  ci: ci.map(([year, lower, upper]) => ({ year, lower, upper })),
  pValue: 0.16129032258064516,
  statistic: 12.602929955114083,
  alpha: 0.1
};

let js = '/* Generated by tools/build-a5-data.mjs; SC path from smoking.csv, CI from the book. */\n';
js += '(function (g) {\n  var data = ' + JSON.stringify(payload) + ';\n';
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n";
js += '  g.A5Data = data;\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
fs.writeFileSync(path.join(root, 'assets/js/data-a5.js'), js);
console.log('wrote assets/js/data-a5.js');
console.log('effect 1988', effect[18], '2000', effect[30]);
