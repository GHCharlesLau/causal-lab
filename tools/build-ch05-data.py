"""Generate assets/js/data-ch05.js from the book's wage.csv.

Run from the project root:
    python tools/build-ch05-data.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "wage.csv"
OUT = ROOT / "assets" / "js" / "data-ch05.js"

df = pd.read_csv(SRC).dropna().copy()
columns = [
    "lhwage", "educ", "IQ", "exper", "tenure", "age",
    "married", "black", "south", "urban", "sibs", "brthord", "meduc", "feduc",
]

payload = {"n": int(len(df))}
for col in columns:
    payload[col] = [round(float(x), 6) for x in df[col]]

js = "/* Generated by tools/build-ch05-data.py from the book's wage.csv (complete cases). */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch05Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes, {len(df)} rows)")
