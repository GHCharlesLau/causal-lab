"""Generate assets/js/data-ch02.js from the book's online_classroom.csv.

Run from the project root:
    python tools/build-ch02-data.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "online_classroom.csv"
OUT = ROOT / "assets" / "js" / "data-ch02.js"

df = pd.read_csv(SRC)


def maybe_int(value):
    return None if pd.isna(value) else int(value)

formats = [
    2 if row.format_ol else 1 if row.format_blended else 0
    for row in df.itertuples()
]

payload = {
    "n": int(len(df)),
    "score": [round(float(x), 5) for x in df.falsexam],
    "format": formats,
    "gender": [maybe_int(x) for x in df.gender],
    "asian": [maybe_int(x) for x in df.asian],
    "black": [maybe_int(x) for x in df.black],
    "hawaiian": [maybe_int(x) for x in df.hawaiian],
    "hispanic": [maybe_int(x) for x in df.hispanic],
    "unknown": [maybe_int(x) for x in df.unknown],
    "white": [maybe_int(x) for x in df.white],
    "labels": ["face-to-face", "blended", "online"],
}

js = "/* Generated by tools/build-ch02-data.py from the book's online_classroom.csv. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch02Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")

