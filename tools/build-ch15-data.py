"""Generate assets/js/data-ch15.js from the book's smoking data and synthetic weights."""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data" / "smoking.csv"
OUT = ROOT / "assets" / "js" / "data-ch15.js"

df = pd.read_csv(SRC)
years = sorted(df.year.unique())
california = df[df.california].set_index("year")["cigsale"]

weights = [
    {"state": 5, "weight": 0.0852},
    {"state": 21, "weight": 0.1130},
    {"state": 22, "weight": 0.1051},
    {"state": 23, "weight": 0.4566},
    {"state": 34, "weight": 0.2401},
]

synthetic = []
for year in years:
    value = 0.0
    for item in weights:
        value += item["weight"] * float(
            df[(df.state == item["state"]) & (df.year == year)]["cigsale"].iloc[0]
        )
    synthetic.append(round(value, 8))

effect = [round(float(california.loc[year]) - synthetic[i], 8) for i, year in enumerate(years)]

placebo_effects = [
    5.79715884, 0.89458993, -24.83015976, -7.16628123, -10.92204876,
    37.11640557, -15.0697173, -0.49805149, -18.45795104, 21.13366442,
    12.57782757, -1.47547828, 10.49627365, -11.67012338, 4.29850835,
    8.04811412, 14.02322417, 8.25002712, 0.32576358, -8.40826863,
    -2.12402716, -7.42865018, 2.96157513, 24.10478118, 4.25211767,
    -17.75844593, 7.93334017, 2.81640126, 12.64955984, -17.47677512,
    -25.16040936, -12.26469139, 24.69067378, 10.36299576, -8.59880354,
]

payload = {
    "years": [int(y) for y in years],
    "california": [round(float(california.loc[y]), 8) for y in years],
    "synthetic": synthetic,
    "effect": effect,
    "weights": weights,
    "weightSum": round(sum(item["weight"] for item in weights), 4),
    "placeboEffects": placebo_effects,
    "californiaEffect2000": effect[-1],
    "pValue": 0.05714285714285714,
    "nStates": int(df.state.nunique()),
    "nPreYears": int((df.after_treatment == False).groupby(df.state).sum().iloc[0]),
    "nPostYears": int((df.after_treatment == True).groupby(df.state).sum().iloc[0]),
}
js = "/* Generated by tools/build-ch15-data.py from smoking.csv and the book's weights. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch15Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes)")
print("effect2000", effect[-1], "weights sum", payload["weightSum"])
print("pre/post", payload["nPreYears"], payload["nPostYears"])
