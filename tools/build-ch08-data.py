"""Generate assets/js/data-ch08.js: AK91 group means + the book's weak-IV simulation."""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
BASE = ROOT.parent / "book-reference" / "causal-inference-for-the-brave-and-true" / "data"
OUT = ROOT / "assets" / "js" / "data-ch08.js"

ak = pd.read_csv(BASE / "ak91.csv")
groups = (
    ak.groupby(["year_of_birth", "quarter_of_birth"])[["log_wage", "years_of_schooling"]]
    .mean()
    .reset_index()
    .sort_values(["year_of_birth", "quarter_of_birth"])
)

# Re-run the book's simulation with the same NumPy seed and design.
np.random.seed(12)
n = 10000
X = np.random.normal(0, 2, n)
U = np.random.normal(0, 2, n)
T = np.random.normal(1 + 0.5 * U, 5, n)
Y = np.random.normal(2 + X - 0.5 * U + 2 * T, 5, n)
stddevs = np.linspace(0.1, 100, 50)
Zs = [np.random.normal(T, s, n) for s in stddevs]


def inv(a):
    return np.linalg.inv(a)


def iv_estimate(z):
    # First stage: T ~ 1 + X + Z
    first = np.column_stack([np.ones(n), X, z])
    gamma = inv(first.T @ first) @ (first.T @ T)
    t_hat = first @ gamma
    # Second stage: Y ~ 1 + X + T_hat
    second = np.column_stack([np.ones(n), X, t_hat])
    beta = inv(second.T @ second) @ (second.T @ Y)
    # Correct 2SLS standard error: structural residual uses actual T.
    resid = Y - (beta[0] + beta[1] * X + beta[2] * T)
    sigma2 = (resid @ resid) / (n - 3)
    cov = sigma2 * inv(second.T @ second)
    se = float(np.sqrt(cov[2, 2]))
    return float(beta[2]), se, float(np.corrcoef(z, T)[0, 1])


rows = []
for z in Zs:
    ate, se, corr = iv_estimate(z)
    rows.append({"corr": round(corr, 8), "ate": round(ate, 8), "se": round(se, 8)})

payload = {
    "ak91": {
        "n": int(len(ak)),
        "groups": {
            "year": [int(x) for x in groups["year_of_birth"]],
            "quarter": [int(x) for x in groups["quarter_of_birth"]],
            "log_wage": [round(float(x), 8) for x in groups["log_wage"]],
            "years": [round(float(x), 8) for x in groups["years_of_schooling"]],
        },
    },
    "weak": {
        "n": int(n),
        "true_ate": 2.0,
        "points": rows,
    },
}
js = "/* Generated by tools/build-ch08-data.py from ak91.csv and the book's seed-12 IV simulation. */\n"
js += "(function (g) {\n  var data = " + json.dumps(payload, separators=(",", ":")) + ";\n"
js += "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
js += "  g.Ch08Data = data;\n})(typeof window !== 'undefined' ? window : globalThis);\n"
OUT.write_text(js, encoding="utf-8")
print(f"wrote {OUT} ({len(js)} bytes, ak91 groups={len(groups)}, weak points={len(rows)})")
print("weak ate range", min(r["ate"] for r in rows), max(r["ate"] for r in rows))
print("weak se range", min(r["se"] for r in rows), max(r["se"] for r in rows))
print("corr range", rows[0]["corr"], rows[-1]["corr"])
print("strongest", rows[0])
